/**
 * Shared WebUI defaults for install, server, and roster URL composition.
 *
 * Port and username are fixed product defaults. The password is never a
 * compile-time secret — `open-panel install` generates and persists it.
 */

/** Default WebUI listen port (`open-panel install` / `open-panel server`). */
export const DEFAULT_WEBUI_PORT = 8888;

/** Fixed WebUI login username (case-sensitive on the wire). */
export const WEBUI_USERNAME = 'administrator';

/** Absolute minimum accepted password length after install. */
export const WEBUI_PASSWORD_MIN_LENGTH = 24;

/** Password length generated by `open-panel install`. */
export const WEBUI_PASSWORD_LENGTH = 32;

/** Alphabet for generated passwords (no ambiguous `0OIl1` glyphs). */
export const WEBUI_PASSWORD_ALPHABET =
    'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!@#$%^&*-_=+';

/** Build the canonical login URL shown after install and in server logs. */
export function webuiLoginUrl(host: string, port: number = DEFAULT_WEBUI_PORT, tls = false): string {
    const scheme = tls ? 'https' : 'http';
    const normalized = host.trim() || '127.0.0.1';
    return `${scheme}://${normalized}:${port}/login`;
}
